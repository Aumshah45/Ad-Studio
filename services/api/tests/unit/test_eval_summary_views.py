"""API views of the eval report (evaluator dashboard follow-ups): typed provenance, summary
warnings, pipeline/agreement passthrough and the SOURCES.md parser. No DB, no network."""

import uuid
from datetime import UTC, datetime

from backend.domain.adstudio.evalreport import (
    FAKE_DRY_RUN_WARNING,
    AgreementMetrics,
    DimensionMetrics,
    EvalReportData,
    PipelineMetrics,
    provenance_of,
    summary_of,
    summary_warnings,
)
from backend.golden.dataset import GOLDEN_DIR
from backend.golden.sources import parse_sources, read_sources


def _data(**kw: object) -> EvalReportData:
    base: dict[str, object] = {
        "report_file": "r.md",
        "created_at": datetime(2026, 1, 1, tzinfo=UTC),
        "evaluator_version": "ev-1",
        "dataset_version": "d1",
        "dry_run": False,
        "per_dimension": {"text": DimensionMetrics(n=1)},
        "counts": {"nat": 2, "final": 2, "plant": 3, "human_labelled": 4},
    }
    base.update(kw)
    return EvalReportData.model_validate(base)


def test_provenance_reads_new_and_legacy_reports() -> None:
    new = provenance_of(
        _data(
            provenance={
                "vision_client": "google",
                "vision_model": "gemini-judge",
                "ocr_engine": "tesseract",
                "ocr_version": "5.5.3",
                "ocr_languages": ["eng", "hin", "jpn"],
                "image_client": ["google"],
                "image_models": ["gemini-image"],
                "image_prompt_versions": ["2"],
                "prompt_versions": {"context_judge": "1", "ad_inspect": "1"},
                "snapshot": "/abs/path/golden/cache/verdicts.json",
                "snapshot_entries": 12,
                "network_attempts": 0,
            }
        )
    )
    assert new.judge_model == "gemini-judge" and new.judge_client == "google"
    assert (new.ocr_engine, new.ocr_version) == ("tesseract", "5.5.3")
    assert new.ocr_languages == ["eng", "hin", "jpn"]
    assert new.prompt_versions == {"context_judge": "1", "ad_inspect": "1"}
    assert new.snapshot_file == "verdicts.json"  # never the absolute local path
    assert new.snapshot_entries == 12 and new.evaluator_version == "ev-1"

    legacy = provenance_of(_data(provenance={"ocr": "tesseract 5.4.0", "image_client": "fake"}))
    assert (legacy.ocr_engine, legacy.ocr_version) == ("tesseract", "5.4.0")
    assert legacy.image_clients == ["fake"] and legacy.ocr_languages == []
    assert provenance_of(_data()).judge_model is None


def test_summary_warnings_flag_dry_run_labels_and_staleness() -> None:
    clean = summary_warnings(
        _data(), current_evaluator_version="ev-1", current_dataset_version="d1"
    )
    assert clean == []

    data = _data(
        dry_run=True,
        counts={"nat": 20, "final": 20, "plant": 36, "human_labelled": 0},
        provenance={"snapshot_evaluator_version": "ev-0", "assume_pass_labels": True},
        warnings=["30/30 pure planted items regenerated byte-identical"],
    )
    warnings = summary_warnings(
        data, current_evaluator_version="ev-2", current_dataset_version="d2"
    )
    assert warnings[0] == FAKE_DRY_RUN_WARNING
    joined = "\n".join(warnings)
    assert "Missing labels" in joined and "Stale snapshot" in joined
    assert "evaluator is now ev-2" in joined and "d1 -> d2" in joined
    assert "assumed all-pass" in joined
    assert warnings[-1] == "30/30 pure planted items regenerated byte-identical"

    partial = summary_warnings(_data(counts={"nat": 2, "final": 2, "human_labelled": 3}))
    assert partial == ["Missing labels: 1 of 4 natural outputs are unlabelled."]


def test_summary_exposes_pipeline_agreement_and_provenance() -> None:
    data = _data(
        pipeline=PipelineMetrics(briefs=2, status_counts={"passed": 1, "needs_review": 1}),
        agreement={"nat": {"text": AgreementMetrics(n=4, agree=3, agreement=0.75, kappa=0.5)}},
        provenance={"vision_model": "judge-x"},
    )
    data.pipeline.mean_repairs = 0.5
    summary = summary_of(uuid.uuid4(), data)
    assert summary.pipeline.mean_repairs == 0.5
    assert summary.pipeline.status_counts == {"passed": 1, "needs_review": 1}
    assert summary.agreement_by_dimension["nat"]["text"].kappa == 0.5
    assert summary.provenance.judge_model == "judge-x"
    assert summary.warnings == []  # default: the report's own warnings + computed ones


def test_sources_parser_reads_the_product_table() -> None:
    _, rows = read_sources(GOLDEN_DIR / "SOURCES.md")
    assert [r.id for r in rows] == ["P1", "P2", "P3", "P4", "P5"]
    p1 = rows[0]
    assert p1.file == "products/P1.jpg" and p1.licence == "CC0 1.0"
    assert p1.source_url and p1.source_url.startswith("https://commons.wikimedia.org/")
    assert p1.licence_url and not p1.share_alike
    assert {r.id for r in rows if r.share_alike} == {"P2", "P3", "P5"}
    assert all(r.author and r.role for r in rows)


def test_sources_parser_ignores_other_tables_and_plain_cells() -> None:
    md = (
        "# x\n\n| a | b |\n|---|---|\n| 1 | 2 |\n\n"
        "| id | File | Role | Source | Author | Licence |\n|---|---|---|---|---|---|\n"
        "| P9 | `products/P9.png` | test | Own photo | Team | CC BY 4.0 |\n\ntrailing\n"
        "| P10 | x | y | z | w | v |\n"
    )
    rows = parse_sources(md)
    assert [r.id for r in rows] == ["P9"]
    assert rows[0].source_url is None and rows[0].source_title == "Own photo"
    assert rows[0].file == "products/P9.png" and rows[0].licence == "CC BY 4.0"
